-- 1)CHECK TOTAL RECORDS 
SELECT 
     COUNT(*) AS TOTAL_RECORDS,
     COUNT(DISTINCT CONTAINER_ID) AS TOTAL_CONTAINERS,
     COUNT(DISTINCT TIMESTAMP) AS UNIQUE_TIMESTAMPS
    FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW;

--CHECK MISSING VALUES
SELECT 
     COUNT_IF(TIMESTAMP IS NULL) AS MISSING_TIMESTAMP,
     COUNT_IF(CONTAINER_ID IS NULL) AS MISSING_CONTAINER,
     COUNT_IF(TEMPERATURE_C IS NULL) AS MISSING_TEMPERATURE,
     COUNT_IF(HUMIDITY_PCT IS NULL) AS MISSING_HUMIDITY,
     COUNT_IF(VIBRATION_G IS NULL) AS MISSING_VIBRATION,
     COUNT_IF(SENSOR_STATUS IS NULL) AS MISSING_STATUS,
     COUNT_IF(RISK_LABEL IS NULL) AS MISSING_RISK
FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW;


-- UNDERSTAND TEMPERATURE AND HUMIDITY
SELECT
    MIN(TEMPERATURE_C) AS MIN_TEMP,
    MAX(TEMPERATURE_C) AS MAX_TEMP,
    AVG(TEMPERATURE_C) AS AVG_TEMP,
    MIN(HUMIDITY_PCT) AS MIN_HUMIDITY,
    MAX(HUMIDITY_PCT) AS MAX_HUMIDITY,
    AVG(HUMIDITY_PCT) AS AVG_HUMIDITY
FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW;



-- CHECK DUPLICATE RECORDS
SELECT 
     COUNT(*) AS TOTAL_RECORDS,
     COUNT(DISTINCT
          CONCAT(
              CONTAINER_ID,
              '_',
              TO_VARCHAR(TIMESTAMP)
          )
    ) AS UNIQUE_READINGS,

    COUNT(*) -
    COUNT(DISTINCT
        CONCAT(
              CONTAINER_ID,
              '_',
              TO_VARCHAR(TIMESTAMP)
        )
    ) AS DUPLICATE_READINGS
FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW;


--OUTLIER DETECTION
SELECT
    MIN(TEMPERATURE_C) AS MIN_TEMP,
    MAX(TEMPERATURE_C) AS MAX_TEMP,
    AVG(TEMPERATURE_C) AS AVG_TEMP,
   
    MIN(HUMIDITY_PCT) AS MIN_HUMIDITY,
    MAX(HUMIDITY_PCT) AS MAX_HUMIDITY,
    
    MIN(VIBRATION_G) AS MIN_VIBRATION,
    MAX(VIBRATION_G) AS MAX_VIBRATION,

    COUNT_IF(HUMIDITY_PCT < 0 OR HUMIDITY_PCT > 100) AS INVALID_HUMIDITY,

    COUNT_IF(TEMPERATURE_C < -40 OR TEMPERATURE_C >60 ) AS EXTREME_TEMPERATURE

FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW;

-- CHECK MISSING CONTAINER IDS
SELECT 
  COUNT(*) AS TOTAL_RECORDS,
  COUNT_IF(CONTAINER_ID IS NULL) AS MISSING_CONTAINER_ID 
FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS;

-- CHECK MISSING VALUES IN COMMODITY MARKET PRICES

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(PRICE_DATE IS NULL) AS MISSING_PRICE_DATE,
    COUNT_IF(COMMODITY IS NULL) AS MISSING_COMMODITY,
    COUNT_IF(MARKET IS NULL) AS MISSING_MARKET,
    COUNT_IF(PRICE_PER_KG_INR IS NULL) AS MISSING_PRICE,
    COUNT_IF(DEMAND_INDEX IS NULL) AS MISSING_DEMAND_INDEX,
    COUNT_IF(MARKET_CAPACITY IS NULL) AS MISSING_MARKET_CAPACITY
FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE;


