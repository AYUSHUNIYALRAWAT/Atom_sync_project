-- 1)VERIFYING RELATION BETWEEN CONTAINER AND SENSOR
SELECT
   C.CONTAINER_ID,
   C.COMMODITY,
   W.TIMESTAMP,
   W.TEMPERATURE_C,
   W.HUMIDITY_PCT,
   W.RISK_LABEL
FROM 
ATOM_SYNC_DB.RAW_DATA.CONTAINERS C 
JOIN
ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW W 
 ON C.CONTAINER_ID = W.CONTAINER_ID
LIMIT 20 ;

