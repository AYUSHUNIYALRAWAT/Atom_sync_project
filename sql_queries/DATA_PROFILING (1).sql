--1) COUNTING ALL RECORDS IN ALL FOUR TABLE
SELECT 'CONTAINERS' AS TABLE_NAME,
       COUNT(*) AS TOTAL_RECORDDS
FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS

UNION ALL

SELECT 'WEATHER_RAW',
  COUNT(*)
FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW

UNION ALL

SELECT 'COMMODITY_MARKET_PRICE',
  COUNT(*)
FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE

UNION ALL 

SELECT 'MARKET_ROUTES',
   COUNT(*)
FROM ATOM_SYNC_DB.RAW_DATA.MARKET_ROUTES;

--CHECK DULICATE SENSOR READING
SELECT 
  COUNT(*)
  TIMESTAMP,
  COUNT(*) AS DUPLICATE_COUNT
FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW
GROUP BY 
    CONTAINER_ID,
    TIMESTAMP
HAVING COUNT(*) > 1
ORDER BY DUPLICATE_COUNT
DESC;


--DUPLICATE DETECTION IN COMMODITY PRICE
SELECT 
   PRICE_DATE,
   COMMODITY,
   MARKET,
   COUNT(*) AS DUPLICATE_COUNT
FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE
GROUP BY 
      PRICE_DATE,
      COMMODITY,
      MARKET
HAVING COUNT(*) > 1
ORDER BY DUPLICATE_COUNT DESC;

-- DUPLICATE DETECTION IN MARKET ROUTES
SELECT
    ORIGIN_MARKET,
    DESTINATION_MARKET,
    COUNT(*) AS DUPLICATE_COUNT
FROM ATOM_SYNC_DB.RAW_DATA.MARKET_ROUTES
GROUP BY 
    ORIGIN_MARKET,
    DESTINATION_MARKET
HAVING COUNT(*) > 1
ORDER BY DUPLICATE_COUNT DESC ;


-- MISSING VALUES ANALYSIS
SELECT 
   COUNT(*) AS TOTAL_RECORDS,
   COUNT_IF(TIMESTAMP IS NULL) AS MISSING_TIMESTAMP,
   COUNT_IF(CONTAINER_ID IS NULL) AS MISSING_CONTAINER,
   COUNT_IF(TEMPERATURE_C IS NULL) AS MISSING_TEMPERATURE,
   COUNT_IF(HUMIDITY_PCT IS NULL) AS MISSING_HUMIDITY,
   COUNT_IF(VIBRATION_G IS NULL) AS MISSING_VIBRATION,
   COUNT_IF(SENSOR_STATUS IS NULL) AS MISSING_SENSOR_STATUS,
   COUNT_IF(RISK_LABEL IS NULL) AS MISSING_RISK_LABEL
FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW



-- CHECK MISSING CONTAINER IDS
SELECT 
  COUNT(*) AS TOTAL_RECORDS,
  COUNT_IF(CONTAINER_ID IS NULL) AS MISSING_CONTAINER_ID 
FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS;

-- CHECK MISSING VALUES IN COMMODITY MARKET PRICES

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(PRICE_DATE IS NULL) AS MISSING_PRICE_DATE,
    COUNT_IF(COMMODITY IS NULL) AS MISSING_COMMODITY,
    COUNT_IF(MARKET IS NULL) AS MISSING_MARKET,
    COUNT_IF(PRICE_PER_KG_INR IS NULL) AS MISSING_PRICE,
    COUNT_IF(DEMAND_INDEX IS NULL) AS MISSING_DEMAND_INDEX,
    COUNT_IF(MARKET_CAPACITY_KG IS NULL) AS MISSING_MARKET_CAPACITY
FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE;


-- check missing values in market_routes
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(ORIGIN_MARKET IS NULL) AS MISSING_ORIGIN,
    COUNT_IF(DESTINATION_MARKET IS NULL) AS MISSING_DESTINATION,
    COUNT_IF(ESTIMATED_DISTANCE_KM IS NULL) AS MISSING_DISTANCE,
    COUNT_IF(ESTIMATED_TRAVEL_HOURS IS NULL) AS MISSING_TRAVEL_HOURS,
    COUNT_IF(EXTRA_TRANSPORT_COST_INR IS NULL) AS MISSING_EXTRA_COST
FROM ATOM_SYNC_DB.RAW_DATA.MARKET_ROUTES;