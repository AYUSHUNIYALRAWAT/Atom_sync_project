        ON C.ORIGIN_MARKET = R.ORIGIN_MARKET
        AND P.MARKET = R.DESTINATION_MARKET
    WHERE P.MARKET <> C.PLANNED_DESTINATION
)
SELECT *
FROM ALTERNATIVE_MARKETS
ORDER BY CONTAINER_ID, ALTERNATIVE_PRICE DESC
