--CHECK TIME SERIES CONTINUITY
WITH READING_INTERVALS AS (
    SELECT
        CONTAINER_ID,
        TIMESTAMP,
        LAG(TIMESTAMP) OVER (
            PARTITION BY CONTAINER_ID
            ORDER BY TIMESTAMP
        ) AS PREVIOUS_TIMESTAMP
    FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW
)
SELECT
    CONTAINER_ID,
    PREVIOUS_TIMESTAMP,
    TIMESTAMP AS CURRENT_TIMESTAMP,
    DATEDIFF(
        MINUTE,
        PREVIOUS_TIMESTAMP,
        TIMESTAMP
    ) AS MINUTES_GAP
FROM READING_INTERVALS
WHERE PREVIOUS_TIMESTAMP IS NOT NULL
  AND DATEDIFF(
      MINUTE,
      PREVIOUS_TIMESTAMP,
      TIMESTAMP
  ) != 15
ORDER BY CONTAINER_ID, CURRENT_TIMESTAMP;


