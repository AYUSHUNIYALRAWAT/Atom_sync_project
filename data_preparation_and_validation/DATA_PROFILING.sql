--BUILD CONTAINER-LEVEL RISK
SELECT
    CONTAINER_ID,
    COMMODITY,
    COUNT(*) AS TOTAL_READINGS,

    ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE,
    ROUND(MAX(TEMPERATURE_C), 2) AS MAX_TEMPERATURE,
    ROUND(MIN(TEMPERATURE_C), 2) AS MIN_TEMPERATURE,

    ROUND(AVG(HUMIDITY_PCT), 2) AS AVG_HUMIDITY,
    ROUND(MAX(HUMIDITY_PCT), 2) AS MAX_HUMIDITY,

    ROUND(AVG(VIBRATION_G), 3) AS AVG_VIBRATION,

    COUNT_IF(RISK_LABEL = 'HIGH') AS HIGH_RISK_READINGS,
    COUNT_IF(RISK_LABEL = 'MEDIUM') AS MEDIUM_RISK_READINGS,
    COUNT_IF(RISK_LABEL = 'LOW') AS LOW_RISK_READINGS

FROM ATOM_SYNC_DB.RAW_DATA.ATMOSYNC_INTEGRATED_VIEW

GROUP BY CONTAINER_ID, COMMODITY
ORDER BY HIGH_RISK_READINGS DESC;

-- CALCULATE CONTAINER ENVIROMENT DEVIATION
WITH READING_DEVIATIONS AS (
    SELECT
        CONTAINER_ID,
        COMMODITY,
        TEMPERATURE_C,
        TARGET_TEMPERATURE_C,
        HUMIDITY_PCT,
        TARGET_HUMIDITY_PCT,

        ABS(TEMPERATURE_C - TARGET_TEMPERATURE_C)
            AS TEMP_DEVIATION,

        ABS(HUMIDITY_PCT - TARGET_HUMIDITY_PCT)
            AS HUMIDITY_DEVIATION

    FROM ATOM_SYNC_DB.RAW_DATA.ATMOSYNC_INTEGRATED_VIEW
)

SELECT
    CONTAINER_ID,
    COMMODITY,

    ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE,
    ROUND(MAX(TEMPERATURE_C), 2) AS MAX_TEMPERATURE,
    ROUND(MAX(TARGET_TEMPERATURE_C), 2) AS TARGET_TEMPERATURE,

    ROUND(AVG(TEMP_DEVIATION), 2) AS AVG_TEMP_DEVIATION,
    ROUND(MAX(TEMP_DEVIATION), 2) AS MAX_TEMP_DEVIATION,

    ROUND(AVG(HUMIDITY_PCT), 2) AS AVG_HUMIDITY,
    ROUND(MAX(TARGET_HUMIDITY_PCT), 2) AS TARGET_HUMIDITY,

    ROUND(AVG(HUMIDITY_DEVIATION), 2)
        AS AVG_HUMIDITY_DEVIATION

FROM READING_DEVIATIONS

GROUP BY CONTAINER_ID, COMMODITY

ORDER BY MAX_TEMP_DEVIATION DESC;


--container level risk scoring 
SELECT
    CONTAINER_ID,
    COMMODITY,

    COUNT(*) AS TOTAL_READINGS,

    COUNT_IF(RISK_LABEL = 'HIGH') AS HIGH_RISK_READINGS,
    COUNT_IF(RISK_LABEL = 'MEDIUM') AS MEDIUM_RISK_READINGS,
    COUNT_IF(RISK_LABEL = 'LOW') AS LOW_RISK_READINGS,

    ROUND(
        100.0 * COUNT_IF(RISK_LABEL = 'HIGH') / NULLIF(COUNT(*), 0),
        2
    ) AS HIGH_RISK_PERCENTAGE,

    ROUND(
        100.0 * (
            3 * COUNT_IF(RISK_LABEL = 'HIGH')
            + 2 * COUNT_IF(RISK_LABEL = 'MEDIUM')
            + COUNT_IF(RISK_LABEL = 'LOW')
        ) / NULLIF(3 * COUNT(*), 0),
        2
    ) AS RISK_SCORE

FROM ATOM_SYNC_DB.RAW_DATA.ATMOSYNC_INTEGRATED_VIEW

GROUP BY CONTAINER_ID, COMMODITY

ORDER BY RISK_SCORE DESC;

--TIME SERIES RISK TREND ANALYSIS
-- STEP 23: DAILY ENVIRONMENTAL RISK TREND

SELECT
    TO_DATE(TIMESTAMP) AS READING_DATE,

    COUNT(*) AS TOTAL_READINGS,

    ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE,
    ROUND(AVG(HUMIDITY_PCT), 2) AS AVG_HUMIDITY,

    COUNT_IF(RISK_LABEL = 'HIGH') AS HIGH_RISK_READINGS,
    COUNT_IF(RISK_LABEL = 'MEDIUM') AS MEDIUM_RISK_READINGS,
    COUNT_IF(RISK_LABEL = 'LOW') AS LOW_RISK_READINGS,

    ROUND(
        100.0 * COUNT_IF(RISK_LABEL = 'HIGH')
        / NULLIF(COUNT(*), 0),
        2
    ) AS HIGH_RISK_PERCENTAGE

FROM ATOM_SYNC_DB.RAW_DATA.ATMOSYNC_INTEGRATED_VIEW

GROUP BY TO_DATE(TIMESTAMP)

ORDER BY READING_DATE;



--: HOURLY HIGH-RISK ANALYSIS

SELECT
    DATE_TRUNC('HOUR', TIMESTAMP) AS READING_HOUR,

    COUNT(*) AS TOTAL_READINGS,

    COUNT_IF(RISK_LABEL = 'HIGH') AS HIGH_RISK_READINGS,

    COUNT_IF(RISK_LABEL = 'MEDIUM') AS MEDIUM_RISK_READINGS,

    ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE,

    ROUND(AVG(HUMIDITY_PCT), 2) AS AVG_HUMIDITY,

    ROUND(
        100.0 * COUNT_IF(RISK_LABEL = 'HIGH')
        / NULLIF(COUNT(*), 0),
        2
    ) AS HIGH_RISK_PERCENTAGE

FROM ATOM_SYNC_DB.RAW_DATA.ATMOSYNC_INTEGRATED_VIEW

GROUP BY DATE_TRUNC('HOUR', TIMESTAMP)

ORDER BY HIGH_RISK_PERCENTAGE DESC;

