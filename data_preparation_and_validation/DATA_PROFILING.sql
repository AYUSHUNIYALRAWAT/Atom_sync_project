SELECT
    C.CONTAINER_ID,
    C.COMMODITY,
    C.QUANTITY_KG,

    C.PLANNED_DESTINATION AS ORIGINAL_MARKET,
    OP.PRICE_PER_KG_INR AS ORIGINAL_PRICE,

    P.MARKET AS ALTERNATIVE_MARKET,
    P.PRICE_PER_KG_INR AS ALTERNATIVE_PRICE,

    P.DEMAND_INDEX,
    P.MARKET_CAPACITY_KG,

    R.EXTRA_TRANSPORT_COST_INR,

    ROUND(
        (P.PRICE_PER_KG_INR - OP.PRICE_PER_KG_INR)
        * C.QUANTITY_KG, 2
    ) AS ADDITIONAL_REVENUE,

    ROUND(
        (P.PRICE_PER_KG_INR - OP.PRICE_PER_KG_INR)
        * C.QUANTITY_KG - R.EXTRA_TRANSPORT_COST_INR, 2
    ) AS NET_REROUTING_VALUE

FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS C

JOIN ORIGINAL_PRICES OP
    ON C.COMMODITY = OP.COMMODITY
    AND C.PLANNED_DESTINATION = OP.MARKET

JOIN ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE P
    ON C.COMMODITY = P.COMMODITY
    AND P.PRICE_DATE = (SELECT PRICE_DATE FROM LATEST_PRICES)
    AND P.MARKET <> C.PLANNED_DESTINATION

JOIN ATOM_SYNC_DB.RAW_DATA.MARKET_ROUTES R
    ON C.ORIGIN_MARKET = R.ORIGIN_MARKET
    AND P.MARKET = R.DESTINATION_MARKET

ORDER BY NET_REROUTING_VALUE DESC;

--COMBINING SHIPMENT RISK WITH REROUTING 
WITH LATEST_PRICES AS (
    SELECT MAX(PRICE_DATE) AS PRICE_DATE
    FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE
),

SHIPMENT_RISK AS (
    SELECT
        CONTAINER_ID,
        COUNT(*) AS TOTAL_READINGS,
        COUNT_IF(RISK_LABEL = 'HIGH') AS HIGH_RISK_READINGS,
        ROUND(
            100.0 * COUNT_IF(RISK_LABEL = 'HIGH')
            / NULLIF(COUNT(*), 0), 2
        ) AS HIGH_RISK_PERCENTAGE,
        ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE,
        ROUND(AVG(HUMIDITY_PCT), 2) AS AVG_HUMIDITY
    FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW
    GROUP BY CONTAINER_ID
),

REROUTING_OPPORTUNITIES AS (
    SELECT
        C.CONTAINER_ID,
        C.COMMODITY,
        C.QUANTITY_KG,
        C.PLANNED_DESTINATION AS ORIGINAL_MARKET,
        OP.PRICE_PER_KG_INR AS ORIGINAL_PRICE,
        P.MARKET AS ALTERNATIVE_MARKET,
        P.PRICE_PER_KG_INR AS ALTERNATIVE_PRICE,
        R.EXTRA_TRANSPORT_COST_INR,
        ROUND(
            (P.PRICE_PER_KG_INR - OP.PRICE_PER_KG_INR)
            * C.QUANTITY_KG - R.EXTRA_TRANSPORT_COST_INR, 2
        ) AS NET_REROUTING_VALUE
    FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS C
    JOIN ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE OP
        ON C.COMMODITY = OP.COMMODITY
        AND C.PLANNED_DESTINATION = OP.MARKET
    JOIN ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE P
        ON C.COMMODITY = P.COMMODITY
        AND P.MARKET <> C.PLANNED_DESTINATION
        AND P.PRICE_DATE = OP.PRICE_DATE
    JOIN LATEST_PRICES LP
        ON OP.PRICE_DATE = LP.PRICE_DATE
    JOIN ATOM_SYNC_DB.RAW_DATA.MARKET_ROUTES R
        ON C.ORIGIN_MARKET = R.ORIGIN_MARKET
        AND P.MARKET = R.DESTINATION_MARKET
)

SELECT
    O.CONTAINER_ID,
    O.COMMODITY,
    O.ORIGINAL_MARKET,
    O.ALTERNATIVE_MARKET,
    S.HIGH_RISK_PERCENTAGE,
    S.AVG_TEMPERATURE,
    S.AVG_HUMIDITY,
    O.NET_REROUTING_VALUE,
    CASE
        WHEN S.HIGH_RISK_PERCENTAGE >= 50
             AND O.NET_REROUTING_VALUE > 0
            THEN 'HIGH PRIORITY'
        WHEN S.HIGH_RISK_PERCENTAGE >= 50
            THEN 'HIGH RISK - LOW FINANCIAL BENEFIT'
        WHEN O.NET_REROUTING_VALUE > 0
            THEN 'FINANCIAL OPPORTUNITY'
        ELSE 'LOW PRIORITY'
    END AS DECISION_CATEGORY

FROM REROUTING_OPPORTUNITIES O
JOIN SHIPMENT_RISK S
    ON O.CONTAINER_ID = S.CONTAINER_ID

ORDER BY
    S.HIGH_RISK_PERCENTAGE DESC,
    O.NET_REROUTING_VALUE DESC;


    --CREATING CONTAINER LEVEL DECISION SUMMARY

    WITH LATEST_PRICES AS (
    SELECT MAX(PRICE_DATE) AS PRICE_DATE
    FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE
),

SHIPMENT_RISK AS (
    SELECT
        CONTAINER_ID,
        COUNT(*) AS TOTAL_READINGS,
        COUNT_IF(RISK_LABEL = 'HIGH') AS HIGH_RISK_READINGS,
        ROUND(
            100.0 * COUNT_IF(RISK_LABEL = 'HIGH')
            / NULLIF(COUNT(*), 0), 2
        ) AS HIGH_RISK_PERCENTAGE
    FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW
    GROUP BY CONTAINER_ID
),

REROUTING AS (
    SELECT
        C.CONTAINER_ID,
        MAX(
            (P.PRICE_PER_KG_INR - OP.PRICE_PER_KG_INR)
            * C.QUANTITY_KG - R.EXTRA_TRANSPORT_COST_INR
        ) AS BEST_NET_REROUTING_VALUE
    FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS C
    JOIN ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE OP
        ON C.COMMODITY = OP.COMMODITY
        AND C.PLANNED_DESTINATION = OP.MARKET
    JOIN ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE P
        ON C.COMMODITY = P.COMMODITY
        AND P.PRICE_DATE = OP.PRICE_DATE
        AND P.MARKET <> C.PLANNED_DESTINATION
    JOIN LATEST_PRICES LP
        ON OP.PRICE_DATE = LP.PRICE_DATE
    JOIN ATOM_SYNC_DB.RAW_DATA.MARKET_ROUTES R
        ON C.ORIGIN_MARKET = R.ORIGIN_MARKET
        AND P.MARKET = R.DESTINATION_MARKET
    GROUP BY C.CONTAINER_ID
)

SELECT
    C.CONTAINER_ID,
    C.COMMODITY,
    S.TOTAL_READINGS,
    S.HIGH_RISK_PERCENTAGE,
    ROUND(R.BEST_NET_REROUTING_VALUE, 2)
        AS BEST_NET_REROUTING_VALUE,
    CASE
        WHEN S.HIGH_RISK_PERCENTAGE >= 50
             AND R.BEST_NET_REROUTING_VALUE > 0
            THEN 'HIGH PRIORITY'
        WHEN S.HIGH_RISK_PERCENTAGE >= 50
            THEN 'OPERATIONAL RISK'
        WHEN R.BEST_NET_REROUTING_VALUE > 0
            THEN 'FINANCIAL OPPORTUNITY'
        ELSE 'NORMAL'
    END AS CONTAINER_DECISION
FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS C
LEFT JOIN SHIPMENT_RISK S
    ON C.CONTAINER_ID = S.CONTAINER_ID
LEFT JOIN REROUTING R
    ON C.CONTAINER_ID = R.CONTAINER_ID
ORDER BY
    S.HIGH_RISK_PERCENTAGE DESC NULLS LAST,
    R.BEST_NET_REROUTING_VALUE DESC NULLS LAST;


--CREATE PERMANENT DESCISION SUPPORT VIEW
CREATE OR REPLACE VIEW
ATOM_SYNC_DB.RAW_DATA.ATMOSYNC_DECISION_VIEW AS

WITH SHIPMENT_RISK AS (
    SELECT
        CONTAINER_ID,
        COUNT(*) AS TOTAL_READINGS,
        COUNT_IF(RISK_LABEL = 'HIGH') AS HIGH_RISK_READINGS,
        ROUND(
            100.0 * COUNT_IF(RISK_LABEL = 'HIGH')
            / NULLIF(COUNT(*), 0), 2
        ) AS HIGH_RISK_PERCENTAGE
    FROM ATOM_SYNC_DB.RAW_DATA.WEATHER_RAW
    GROUP BY CONTAINER_ID
),

LATEST_PRICES AS (
    SELECT MAX(PRICE_DATE) AS PRICE_DATE
    FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE
),

REROUTING AS (
    SELECT
        C.CONTAINER_ID,
        MAX(
            (P.PRICE_PER_KG_INR - OP.PRICE_PER_KG_INR)
            * C.QUANTITY_KG - R.EXTRA_TRANSPORT_COST_INR
        ) AS BEST_NET_REROUTING_VALUE
    FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS C
    JOIN ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE OP
        ON C.COMMODITY = OP.COMMODITY
        AND C.PLANNED_DESTINATION = OP.MARKET
    JOIN ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE P
        ON C.COMMODITY = P.COMMODITY
        AND P.PRICE_DATE = OP.PRICE_DATE
        AND P.MARKET <> C.PLANNED_DESTINATION
    JOIN LATEST_PRICES LP
        ON OP.PRICE_DATE = LP.PRICE_DATE
    JOIN ATOM_SYNC_DB.RAW_DATA.MARKET_ROUTES R
        ON C.ORIGIN_MARKET = R.ORIGIN_MARKET
        AND P.MARKET = R.DESTINATION_MARKET
    GROUP BY C.CONTAINER_ID
)

SELECT
    C.CONTAINER_ID,
    C.COMMODITY,
    C.QUANTITY_KG,
    C.ORIGIN_MARKET,
    C.PLANNED_DESTINATION,
    S.TOTAL_READINGS,
    S.HIGH_RISK_PERCENTAGE,
    R.BEST_NET_REROUTING_VALUE,
    CASE
        WHEN S.HIGH_RISK_PERCENTAGE >= 50
             AND R.BEST_NET_REROUTING_VALUE > 0
            THEN 'HIGH PRIORITY'
        WHEN S.HIGH_RISK_PERCENTAGE >= 50
            THEN 'OPERATIONAL RISK'
        WHEN R.BEST_NET_REROUTING_VALUE > 0
            THEN 'FINANCIAL OPPORTUNITY'
        ELSE 'NORMAL'
    END AS CONTAINER_DECISION
FROM ATOM_SYNC_DB.RAW_DATA.CONTAINERS C
LEFT JOIN SHIPMENT_RISK S
    ON C.CONTAINER_ID = S.CONTAINER_ID
LEFT JOIN REROUTING R
    ON C.CONTAINER_ID = R.CONTAINER_ID;

