WITH LATEST_PRICES AS (
    SELECT MAX(PRICE_DATE) AS PRICE_DATE
    FROM ATOM_SYNC_DB.RAW_DATA.COMMODITY_MARKET_PRICE
),
ALTERNATIVE_MARKETS AS (
    SELECT
        C.CONTAINER_ID,
        C.COMMODITY,
        C.QUANTITY_KG,
        C.ORIGIN_MARKET,
        C.PLANNED_DESTINATION AS ORIGINAL_MARKET,
